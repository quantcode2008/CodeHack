import * as React from "react";
import { cn } from "@/lib/utils";

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  interactive?: boolean;
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, interactive = false, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        "bg-surface text-ink border border-line rounded-editorial p-6 shadow-editorial transition-all duration-150",
        interactive &&
          "cursor-pointer hover:border-ink/30 hover:shadow-editorial-raised active:translate-y-[1px]",
        className
      )}
      {...props}
    />
  )
);
Card.displayName = "Card";

